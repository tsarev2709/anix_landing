const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/lib/industryBrief.js'), 'utf8');
const data = JSON.parse(fs.readFileSync(path.join(root, 'src/content/industryForms.json'), 'utf8'));
const generated = '// Generated by scripts/sync-industry-brief.js. Edit src/lib/industryBrief.js and src/content/industryForms.json.\n' + source.replace("import industryForms from '../content/industryForms.json';", `const industryForms = ${JSON.stringify(data)};`);
const target = path.join(root, 'supabase/functions/_shared/industry-brief.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== generated) throw new Error('Industry brief server copy is stale. Run node scripts/sync-industry-brief.js');
} else fs.writeFileSync(target, generated);
console.log('Industry brief schema synchronized');
