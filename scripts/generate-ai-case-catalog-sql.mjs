import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = path.join(root, 'data', 'ai-public-cases.json');
const migrationPath = path.join(
  root,
  'supabase',
  'migrations',
  '009_ai_consultant_structured_cases.sql'
);

function sql(value) {
  if (value === null || value === undefined) return 'null';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function json(value) {
  return `${sql(JSON.stringify(value))}::jsonb`;
}

function normalizedAlias(value) {
  return String(value || '')
    .toLowerCase()
    .replaceAll('ё', 'е')
    .replace(/[^a-zа-я0-9]+/gi, ' ')
    .trim();
}

const catalog = JSON.parse(await fs.readFile(catalogPath, 'utf8'));
const clients = new Map();
for (const item of catalog.cases) {
  if (item.client) clients.set(item.client.slug, item.client);
}

const clientRows = [...clients.values()]
  .map(
    (item) =>
      `  (${sql(item.slug)}, ${sql(item.name)}, ${json(item.aliases || [])}, true)`
  )
  .join(',\n');

const caseRows = catalog.cases
  .map(
    (item) => `  (
    ${sql(item.slug)}, ${sql(item.client?.slug)}, ${sql(item.displayName)},
    ${sql(item.vertical)}, ${sql(item.category)}, ${sql(item.title)},
    ${sql(item.summary)}, ${sql(item.task)}, ${sql(item.solution)}, ${sql(item.result)},
    ${json(item.tags || [])}, ${sql(item.publicUrl)}, ${Number(item.sortOrder || 0)}, true
  )`
  )
  .join(',\n');

const aliasRows = catalog.cases
  .flatMap((item) =>
    [...new Map(
      [item.displayName, ...(item.aliases || [])].map((alias) => [
        normalizedAlias(alias),
        alias,
      ])
    ).values()].map((alias) => `  (${sql(item.slug)}, ${sql(alias)})`)
  )
  .join(',\n');

const claimRows = catalog.cases
  .flatMap((item) =>
    ['summary', 'task', 'solution', 'result'].map(
      (kind) =>
        `  (${sql(item.slug)}, ${sql(kind)}, ${sql(item[kind])}, ${sql(item.publicUrl)}, true)`
    )
  )
  .join(',\n');

const assetRows = catalog.cases
  .flatMap((item) => [
    [item.slug, 'case_page', 'Открыть кейс', item.publicUrl],
    ...(item.imageUrl
      ? [[item.slug, 'image', 'Изображение кейса', item.imageUrl]]
      : []),
    ...(item.videoUrl
      ? [[item.slug, 'video', 'Смотреть видео', item.videoUrl]]
      : []),
  ])
  .map(
    ([slug, kind, label, url]) =>
      `  (${sql(slug)}, ${sql(kind)}, ${sql(label)}, ${sql(url)}, true)`
  )
  .join(',\n');

