const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/lib/attribution.js'), 'utf8');
const target = path.join(root, 'supabase/functions/_shared/attribution.ts');
const expected = '// @ts-nocheck\n// Generated by scripts/sync-attribution.js. Edit src/lib/attribution.js.\n' + source;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected.replace(/\r\n/g, '\n')) throw new Error('Attribution contract is out of sync');
} else fs.writeFileSync(target, expected);
